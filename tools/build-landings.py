def section(inner, alt=False, sid=None, narrow=True):
    cls = 'lp-section lp-alt' if alt else 'lp-section'
    idattr = f' id="{sid}"' if sid else ''
    wrap = 'lp-narrow' if narrow else 'lp-container'
    return f'''
    <section class="{cls}"{idattr}>
        <div class="{wrap}">
{inner}
        </div>
    </section>
'''


